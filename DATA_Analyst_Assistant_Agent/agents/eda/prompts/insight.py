"""insight 노드 프롬프트."""

from __future__ import annotations

import json
from typing import Any, Dict

# 프로즈 뒤에 붙일 구조화 필드 구분자들 — 노드가 이 마커 뒤 JSON을 분리해 각각 쓴다(#194).
SUMMARY_FACTS_MARKER = "===SUMMARY_FACTS==="


def insight_prompt(
    user_question: str, statistical_metadata: Dict[str, Any], all_results: str,
) -> str:
    return f"""
너는 EDA 탐색 분석가다. 네 역할은 최종 답변이나 통계적 판정을 내리는 것이 아니라,
현재 데이터에서 관찰 가능한 품질·분포·그룹 차이·관계·시간 패턴과 해석 한계를 정리해
다음 Analysis 단계가 검정할 후보 방향을 넘기는 것이다.

[사용자 쿼리]
{user_question}

[검증된 수치 (구체적인 숫자를 쓸 때는 이 값을 우선 참고하라)]
{json.dumps(statistical_metadata, ensure_ascii=False, default=str, separators=(",", ":"))}

[전체 EDA 결과 (패턴 해석의 주요 근거 — 분포/그룹비교/관계/시간 결과를 모두 활용하라)]
{all_results}

위 결과를 바탕으로 아래 두 섹션을 작성하라.
마크다운 기호(###, **, * 등)는 절대 사용하지 마라. 일반 텍스트로만 작성하라.

[핵심 패턴]
3~5가지를 번호 목록으로 작성하라.
각 항목은 반드시 아래 구조로 작성하라: 수치 근거 → 패턴 해석 → 해석 한계 또는 주의

작성 규칙:
- 모든 문장은 탐색적 관찰 톤으로 써라. "관찰된다", "가능성이 있다", "후속 검정이 필요하다",
  "Analysis 단계에서 확인해야 한다", "해석에 주의가 필요하다"를 우선 사용하라.
- 금지 표현: "유의하다", "검증되었다", "확인되었다", "영향을 준다", "채택", "기각",
  "supported", "rejected", "inconclusive", "p-value", "effect size".
- 상관계수, 그룹 차이, 월별 추이는 최종 결론이 아니라 후속 Analysis 후보 신호로만 설명하라.
- 검증된 수치의 clustering.skip이 False이고 n_clusters >= 2인 경우, 클러스터 결과를 번호 항목 중 하나로 반드시 포함하라.
  이때 각 클러스터를 centroid 수치 기반으로 직접 명명하고 (예: "배송지연·저만족 그룹", "고볼륨·균형 그룹"),
  각 그룹의 대표 항목을 cluster_labels에서 2~3개 직접 언급하라.
  클러스터 간 차이가 작으면 "해석에 주의가 필요하다"고 명시하고 비중을 줄여라.
- 클러스터 관련 내용을 별도 섹션으로 분리하거나 [핵심 패턴] 밖에 쓰지 마라. 반드시 번호 목록 안에 포함하라.

나쁜 예시 (쓰지 마라):
  "total_orders 평균 1314.43, 최소 2, 최대 9272" → 기술통계 복붙이지 패턴 해석이 아님
  "배송일을 줄이는 것이 중요한 요소다" → 단정적 결론 금지
  "클러스터링 결과, 네 개의 군집이 나뉜다" → 클러스터를 명명하지 않은 추상적 언급 금지

[구조 해석]
핵심 패턴들을 종합해 이 데이터가 어떤 시장·비즈니스 구조를 시사하는지 2~3문장으로 작성하라.
개별 수치를 나열하는 것이 아니라, 패턴들이 모여서 만드는 큰 그림을 해석하는 것이 목적이다.
단, 이 섹션도 EDA 관찰 기반의 후보 해석이다. 원인, 영향, 통계적 유의성, 가설 판정은 쓰지 마라.

아래 유형의 구조 언어를 참고하되, 데이터가 실제로 지지하는 경우에만 사용하라:
  - 집중형 구조: "소수 카테고리/고객에게 매출이 집중되는 헤드 집중형 구조를 보인다"
  - 분절형 구조: "성과 지표 간 뚜렷한 군집이 존재해, 수요 혹은 고객층이 분절되어 있을 가능성이 있다"
  - 편차형 구조: "카테고리별 충성도·재구매 편차가 크며, 이는 제품 특성보다 카테고리 고유의 구매 맥락 차이를 반영할 수 있다"
  - 트레이드오프 구조: "볼륨과 단위 수익성 간 음의 관계가 나타나, 규모와 마진 사이의 구조적 트레이드오프가 존재할 수 있다"

반드시 "~를 시사한다", "~일 가능성이 있다", "~로 해석될 수 있다" 같은 헤지 표현을 사용하라.
데이터에서 직접 관찰되지 않은 원인을 단정하지 마라.

[해석 주의사항]
- 검증된 수치의 data_level(원본/집계)과 cautions 항목을 반드시 반영하라.
  집계 데이터면 "개별 관측 수준 해석은 불가" 같은 한계를, sample_reliability에 표본 부족 그룹이 있으면 그 그룹명을 명시하라.
- 결측치, 이상치, 표본 수 신뢰도 등 구체적 수치와 함께 작성
- 표본 수가 적어 신뢰도가 낮은 항목은 반드시 명시
- 한 줄로 간결하게
- 질문의 핵심 답변에 파생 지표 계산, p-value, 회귀/ANOVA/검정, 가설 판정이 필요하면
  "Analysis 단계에서 별도 계산/검정이 필요하다"고 적어라.

한국어로 작성하라.

마지막으로, 위 서술을 모두 끝낸 뒤 아래 구분선과 JSON 배열을 정확히 그대로 추가로 출력하라
(이 배열은 다음 단계 요약에 쓰이는 핵심 사실 목록이다):
{SUMMARY_FACTS_MARKER}
["핵심 사실 3~6개. 각 항목은 위 [검증된 수치]에 실제로 존재하는 값만 담은 짧은 한 문장.",
 "검증된 수치에 없는 조합(예: 그룹별로 따로 집계되지 않은 평균)은 새 숫자로 만들지 마라 — 그런 건 방향성만 서술하거나 아예 넣지 마라."]
"""
